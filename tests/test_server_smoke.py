"""Protect the EULA boundary and truthful server-bootstrap reporting offline."""

import contextlib
import importlib.util
import io
from pathlib import Path
import tempfile
import unittest
from unittest import mock


SPEC = importlib.util.spec_from_file_location(
    "server_smoke", Path(__file__).parents[1] / "tools/server_smoke.py")
server_smoke = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(server_smoke)


class EulaSafetyTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.eula = self.root / "run/server/eula.txt"
        self.eula.parent.mkdir(parents=True)

    def tearDown(self):
        self.temporary.cleanup()

    def assert_launch_refused_without_modifying(self, contents):
        self.eula.write_bytes(contents)
        with mock.patch.object(server_smoke, "ROOT", self.root), \
                mock.patch.object(server_smoke.subprocess, "Popen") as launch, \
                mock.patch("sys.argv", ["server_smoke.py"]), \
                contextlib.redirect_stderr(io.StringIO()), \
                self.assertRaises(SystemExit) as result:
            server_smoke.main()
        self.assertEqual(result.exception.code, 2)
        launch.assert_not_called()
        self.assertEqual(self.eula.read_bytes(), contents)
        self.assertFalse((self.root / "build").exists())

    def test_missing_or_declined_eula_is_only_inspected(self):
        self.assertFalse(server_smoke.eula_is_accepted(self.eula))
        self.assertFalse(self.eula.exists())
        contents = b"# Generated by Minecraft\neula=false\n"
        self.eula.write_bytes(contents)
        self.assertFalse(server_smoke.eula_is_accepted(self.eula))
        self.assertEqual(self.eula.read_bytes(), contents)

    def test_accepted_eula_refuses_launch_and_preserves_bytes(self):
        for contents in (b"eula=true\n", b"! comment\neula : TRUE\r\n",
                         b"eula true\n", b"eula=false\neula=true\n"):
            with self.subTest(contents=contents):
                self.assert_launch_refused_without_modifying(contents)

    def test_unicode_escaped_values_and_keys_refuse_launch(self):
        for contents in (b"eula=tr\\u0075e\n", b"eu\\u006ca=true\n",
                         b"\\u0065ula=true\n"):
            with self.subTest(contents=contents):
                self.assert_launch_refused_without_modifying(contents)

    def test_java_continuations_refuse_launch(self):
        for contents in (b"eula=tr\\\nue\n", b"eu\\\nla=true\n",
                         b"eula=\\\r\n true\r\n"):
            with self.subTest(contents=contents):
                self.assert_launch_refused_without_modifying(contents)

    def test_unfamiliar_properties_refuse_launch(self):
        for contents in (b"eula=yes\n", b"unrelated=true\n", b"eula=\xff\n"):
            with self.subTest(contents=contents):
                self.assert_launch_refused_without_modifying(contents)


class BootstrapClassificationTests(unittest.TestCase):
    # Deliberately use different pins to catch accidental version duplication.
    VERSIONS = {"minecraft_version": "1.22.4", "loader_version": "0.25.7",
                "mod_version": "2.3.4"}
    OUTPUT = (
        "[main/INFO] (FabricLoader/GameProvider) Loading Minecraft 1.22.4 "
        "with Fabric Loader 0.25.7\n"
        "[main/INFO] (FabricLoader) Loading 3 mods:\n"
        "\t- balance 2.3.4\n"
        "[main/INFO] (balance) Balance development foundation initialized\n"
        "[ServerMain/INFO] You need to agree to the EULA in order to run the server. "
        "Go to eula.txt for more info.\n"
        "BUILD SUCCESSFUL in 14s\n"
    )

    def result(self, output=None, exit_code=0):
        return server_smoke.check_output(self.OUTPUT if output is None else output,
                                         exit_code, self.VERSIONS)

    def test_full_bootstrap_evidence_reports_only_its_actual_scope(self):
        result = self.result()
        self.assertEqual(result["outcome"], "eula_boundary_verified")
        self.assertEqual(result["gradle_exit_code"], 0)
        self.assertFalse(result["gameplay_tested"])
        self.assertTrue(result["mod_initializer_tested"])

    def test_missing_loader_mod_or_eula_evidence_fails(self):
        lines = self.OUTPUT.splitlines(keepends=True)
        for excluded in (0, 2, 3, 4):
            with self.subTest(excluded=excluded):
                self.assertEqual(self.result("".join(
                    line for index, line in enumerate(lines) if index != excluded
                ))["outcome"], "failed")
        missing_initializer = self.result(self.OUTPUT.replace(
            "Balance development foundation initialized", ""))
        self.assertFalse(missing_initializer["mod_initializer_tested"])

    def test_similar_but_wrong_version_banners_fail(self):
        for old, replacement in (("Minecraft 1.22.4", "Minecraft 1.22.40"),
                                 ("Loader 0.25.7", "Loader 0.25.70"),
                                 ("Loader 0.25.7", "Loader 0.25.7-beta"),
                                 ("balance 2.3.4", "balance 2.3.40")):
            with self.subTest(replacement=replacement):
                self.assertEqual(self.result(self.OUTPUT.replace(old, replacement))[
                    "outcome"], "failed")

    def test_nonzero_exit_never_becomes_success_from_old_log_text(self):
        for exit_code in (1, -15):
            with self.subTest(exit_code=exit_code):
                result = self.result(exit_code=exit_code)
                self.assertEqual(result["outcome"], "failed")
                self.assertEqual(result["gradle_exit_code"], exit_code)

    def test_unrelated_build_failure_invalidates_previous_success_evidence(self):
        for failure in ("BUILD FAILED in 1s", "A problem occurred evaluating root project",
                        "Exception in thread main", "Caused by: java.io.IOException",
                        "Crash report saved"):
            with self.subTest(failure=failure):
                self.assertEqual(self.result(self.OUTPUT + failure)["outcome"], "failed")
        self.assertEqual(self.result(self.OUTPUT.replace("BUILD SUCCESSFUL", ""))[
            "outcome"], "failed")

    def test_versions_are_read_from_project_properties(self):
        with tempfile.TemporaryDirectory() as directory:
            properties = Path(directory) / "gradle.properties"
            properties.write_text(
                "# project pins\nminecraft_version=1.22.4\nloader_version=0.25.7\n"
                "mod_version=2.3.4\norg.gradle.workers.max=2\n", encoding="utf-8")
            versions = server_smoke.expected_versions(properties)
            self.assertEqual(versions, self.VERSIONS)
            with mock.patch.object(server_smoke, "expected_versions", return_value=versions):
                self.assertEqual(server_smoke.check_output(self.OUTPUT, 0)["outcome"],
                                 "eula_boundary_verified")

    def test_incomplete_properties_fail_closed(self):
        with tempfile.TemporaryDirectory() as directory:
            properties = Path(directory) / "gradle.properties"
            properties.write_text("minecraft_version=1.22.4\nloader_version=\n",
                                  encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "Missing project version pins"):
                server_smoke.expected_versions(properties)


if __name__ == "__main__":
    unittest.main()
